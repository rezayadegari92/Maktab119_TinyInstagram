from django.contrib import admin
from django.urls import path, include
from django.conf import settings
from django.conf.urls.static import static
from django.http import JsonResponse
from drf_spectacular.views import SpectacularAPIView, SpectacularRedocView, SpectacularSwaggerView


def health_check(request):
    """Simple health check endpoint for Docker"""
    return JsonResponse({"status": "healthy", "service": "tiny-instagram"})


urlpatterns = [
    path('admin/', admin.site.urls),

    # Health check
    path('health/', health_check, name='health-check'),

    # API endpoints
    path('api/accounts/', include('accounts.api.v1.urls')),
    path('api/socials/', include('socials.api.v1.urls')),

    # Swagger/OpenAPI Documentation
    path('api/schema/', SpectacularAPIView.as_view(), name='schema'),
    path('api/docs/', SpectacularSwaggerView.as_view(url_name='schema'), name='swagger-ui'),
    path('api/redoc/', SpectacularRedocView.as_view(url_name='schema'), name='redoc'),

    # Template views (removed - using API only)
    # path('', include('accounts.urls')),
    # path('', include('socials.urls')),
]

if settings.DEBUG:
    urlpatterns += static(settings.MEDIA_URL, document_root=settings.MEDIA_ROOT)
    urlpatterns += static(settings.STATIC_URL, document_root=settings.STATIC_ROOT)